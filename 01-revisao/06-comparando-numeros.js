let numero1 = 25;
let numero2 = 18;

if (numero1 > numero2){
console.log(`${numero1} é maior que ${numero2}.`);
}
else if(numero1 < numero2){
    console.log(`${numero2} é maior que ${numero1}.`);
}
else{
    console.log(`${numero1} e ${numero2} são iguais.`);
}